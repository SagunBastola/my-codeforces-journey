void solve()
{
    ll n;
    cin>>n;
    ll total=9;
    ll ans=0;

    ll factor=1;
    while(total <= n*n)
    {
        
        ans=ans+(8)*factor*factor;
        factor++;
        total+=8*factor;
    }
    cout<<ans<<endl;
}
